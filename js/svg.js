// Helper function to insert SVGs into DOM elements
export function insertSVGs() {
  document.querySelectorAll('[data-icon]').forEach(el => {
    const iconName = el.getAttribute('data-icon');
    let svgString = '';
    
    switch (iconName) {
      case 'ampulheta': svgString = svgAmpulheta; break;
      case 'calendario': svgString = svgCalendario; break;
      case 'check': svgString = svgCheck; break;
      case 'deni': svgString = svgDeni; break;
      case 'filtro': svgString = svgFiltro; break;
      case 'edit': svgString = svgEdit; break;
      case 'folder-clock': svgString = svgFolderClock; break;
      case 'clipboard-list': svgString = svgClipboardList; break;
      case 'map-pin': svgString = svgMapPin; break;
      case 'user-shield': svgString = svgUserShield; break;
      case 'employee-user': svgString = svgEmployeeUser; break;
      case 'save': svgString = svgSave; break;
      case 'lightbulb': svgString = svgLightbulb; break;
      case 'info': svgString = svgInfo; break;
      case 'search': svgString = svgSearch; break;
    }
    
    if (svgString && !el.innerHTML.includes('<svg')) {
      el.innerHTML = svgString + el.innerHTML;
    }
  });
}

